const ROW_HEIGHT = 92;
const PAD_Y = 36;
const MIN_COL_WIDTH = 96;
const VIEWBOX_W = 1000;

// Layered Hasse diagram layout: one row per field degree [L^H : Q] = [G : H],
// with nodes in each row ordered by a few barycenter sweeps to cut crossings.
function computeLayout(nodes, edges) {
  const degrees = [...new Set(nodes.map((n) => n.field_degree))].sort((a, b) => a - b);
  const rowOf = new Map(nodes.map((n) => [n.id, degrees.indexOf(n.field_degree)]));
  const rows = degrees.map((d) =>
    nodes
      .filter((n) => n.field_degree === d)
      .sort((a, b) => a.class_id - b.class_id || a.class_position - b.class_position)
      .map((n) => n.id)
  );

  const neighbors = new Map(nodes.map((n) => [n.id, []]));
  for (const [a, b] of edges) {
    neighbors.get(a).push(b);
    neighbors.get(b).push(a);
  }

  const pos = new Map();
  const assign = () =>
    rows.forEach((row) => row.forEach((id, i) => pos.set(id, (i + 0.5) / row.length)));
  assign();

  const sweep = (rowIndices) => {
    for (const r of rowIndices) {
      const bary = (id) => {
        const adj = neighbors.get(id).filter((m) => rowOf.get(m) !== r);
        return adj.length ? adj.reduce((s, m) => s + pos.get(m), 0) / adj.length : pos.get(id);
      };
      const scores = new Map(rows[r].map((id) => [id, bary(id)]));
      rows[r].sort((a, b) => scores.get(a) - scores.get(b));
      rows[r].forEach((id, i) => pos.set(id, (i + 0.5) / rows[r].length));
    }
  };
  const up = rows.map((_, i) => i).slice(1);
  const down = [...up].reverse().slice(1).concat(0);
  for (let k = 0; k < 4; k++) {
    sweep(up);
    sweep(down);
  }

  return { rowOf, pos, rowCount: rows.length, maxRow: Math.max(...rows.map((r) => r.length)) };
}

// Transitive closure along covering edges [smaller subgroup, larger subgroup].
function reach(start, adjacency) {
  const seen = new Set();
  const stack = [start];
  while (stack.length) {
    const cur = stack.pop();
    for (const next of adjacency.get(cur) || []) {
      if (!seen.has(next)) {
        seen.add(next);
        stack.push(next);
      }
    }
  }
  return seen;
}

// Label on the left, value on the right; the value column is minmax(0, 1fr)
// so FitMath can size math to it without a scroll box.
const Fact = ({ label, children }) => (
  <div className="grid grid-cols-1 sm:grid-cols-[auto_minmax(0,1fr)] items-center gap-x-4 gap-y-0.5 py-1.5 border-b border-gray-900 last:border-b-0">
    <span className="text-xs uppercase tracking-widest text-gray-500">{label}</span>
    <div className="text-gray-100 sm:text-right">{children}</div>
  </div>
);

function NodeDetails({ node, groupOrder }) {
  if (!node) {
    return (
      <p className="text-sm text-gray-500">
        Hover or tap a node to see its fixed field <MathDisplay inline>{"L^H"}</MathDisplay> and subgroup{" "}
        <MathDisplay inline>{"H"}</MathDisplay> side by side.
      </p>
    );
  }

  const m = (tex, breakable = false) => (
    <FitMath align="end" breakable={breakable}>
      {tex}
    </FitMath>
  );

  return (
    <div className="grid md:grid-cols-2 gap-x-8">
      <div>
        <h4 className="text-sm uppercase tracking-[0.2em] text-accent-300 mb-2">Field</h4>
        <Fact label="Fixed field">{m(`F = ${node.field_latex}`)}</Fact>
        <Fact label="Degree">{m(`[F : \\mathbb{Q}] = ${node.field_degree}`)}</Fact>
        {node.field_degree > 1 && (
          <>
            <Fact label="Generator">{m("F = \\mathbb{Q}(\\beta)")}</Fact>
            <Fact label="Min. polynomial">{m(`m_{\\beta}(x) = ${node.field_polynomial}`, true)}</Fact>
          </>
        )}
        <Fact label={<>Galois over <Rationals /></>}>
          {node.normal ? (node.quotient_latex ? m(`\\text{yes, }\\mathrm{Gal}(F/\\mathbb{Q}) \\cong ${node.quotient_latex}`) : "Yes") : "No"}
        </Fact>
        {node.class_size > 1 && (
          <p className="text-xs text-gray-500 mt-2 leading-relaxed">
            One of {node.class_size} conjugate subfields of <MathDisplay inline>{"L"}</MathDisplay>: isomorphic as
            fields, but distinct inside <MathDisplay inline>{"L"}</MathDisplay>.
          </p>
        )}
        {node.is_stem_field && (
          <p className="text-xs text-gray-500 mt-2 leading-relaxed">
            Isomorphic to <MathDisplay inline>{"\\mathbb{Q}(\\alpha) \\cong \\mathbb{Q}[x]/(f)"}</MathDisplay>, the
            field generated by a single root of <MathDisplay inline>{"f"}</MathDisplay>.
          </p>
        )}
      </div>
      <div className="mt-4 md:mt-0">
        <h4 className="text-sm uppercase tracking-[0.2em] text-accent-300 mb-2">Subgroup</h4>
        <Fact label="Subgroup">{m(`H = \\mathrm{Gal}(L/F) \\cong ${node.group_latex}`)}</Fact>
        <Fact label="Generated by">
          {m(node.generators?.length ? `H = \\langle ${node.generators.join(",\\ ")} \\rangle` : "H = \\{\\mathrm{id}\\}")}
        </Fact>
        <Fact label="Order">{m(`|H| = ${node.subgroup_order}`)}</Fact>
        <Fact label="Index">{m(`[G : H] = ${groupOrder} / ${node.subgroup_order} = ${node.index}`)}</Fact>
        <Fact label="Normal">{node.normal ? m("\\text{yes, } H \\trianglelefteq G") : "No"}</Fact>
        <p className="text-xs text-gray-500 mt-2 leading-relaxed">
          {node.normal ? (
            <>
              <MathDisplay inline>{"gHg^{-1} = H"}</MathDisplay> for every{" "}
              <MathDisplay inline>{"g \\in G"}</MathDisplay>: no other subgroup is conjugate to it. That is exactly
              why its fixed field is Galois over <Rationals />.
            </>
          ) : (
            <>
              Conjugate to {node.class_size - 1} other subgroup{node.class_size > 2 ? "s" : ""} (
              <MathDisplay inline>{"gHg^{-1} \\neq H"}</MathDisplay> for some{" "}
              <MathDisplay inline>{"g \\in G"}</MathDisplay>), so it isn't normal, and its fixed field isn't Galois
              over <Rationals />. Normality depends on how <MathDisplay inline>{"H"}</MathDisplay> sits inside{" "}
              <MathDisplay inline>{"G"}</MathDisplay>, not on its isomorphism type: other subgroups isomorphic to{" "}
              <MathDisplay inline>{node.group_latex}</MathDisplay> can still be normal.
            </>
          )}
        </p>
      </div>
    </div>
  );
}

function LatticeDiagram({ lattice, view, activeId, onHover, onSelect }) {
  const { nodes, edges } = lattice;
  const layout = useMemo(() => computeLayout(nodes, edges), [nodes, edges]);

  const { below, above } = useMemo(() => {
    if (activeId == null) return { below: new Set(), above: new Set() };
    const supergroups = new Map();
    const subgroups = new Map();
    for (const [a, b] of edges) {
      supergroups.set(a, [...(supergroups.get(a) || []), b]);
      subgroups.set(b, [...(subgroups.get(b) || []), a]);
    }
    // In field terms: supergroups of H fix smaller fields (subfields of L^H).
    return { below: reach(activeId, supergroups), above: reach(activeId, subgroups) };
  }, [activeId, edges]);

  const height = PAD_Y * 2 + (layout.rowCount - 1) * ROW_HEIGHT;
  const fieldsView = view === "fields";
  // Fields: L on top, Q at the bottom. Subgroups: G on top, 1 at the bottom (the same picture, flipped).
  const yOf = (id) => {
    const row = layout.rowOf.get(id);
    return PAD_Y + (fieldsView ? layout.rowCount - 1 - row : row) * ROW_HEIGHT;
  };
  const xOf = (id) => layout.pos.get(id) * VIEWBOX_W;

  const isOnChain = (a, b) =>
    activeId != null &&
    ((a === activeId || above.has(a) || below.has(a)) && (b === activeId || above.has(b) || below.has(b))) &&
    !(above.has(a) && below.has(b)) &&
    !(below.has(a) && above.has(b));

  const byId = new Map(nodes.map((n) => [n.id, n]));
  const showAllEdgeDegrees = nodes.length <= 10;

  return (
    // Wide lattices scroll sideways on narrow screens; overflow-y must be explicit,
    // or overflow-x: auto turns it into a vertical scroll box too.
    <div className="overflow-x-auto overflow-y-hidden border border-gray-800 bg-black">
      <div
        className="relative"
        style={{ height, minWidth: layout.maxRow * MIN_COL_WIDTH }}
        onMouseLeave={() => onHover(null)}
      >
        <svg
          className="absolute inset-0 w-full h-full"
          viewBox={`0 0 ${VIEWBOX_W} ${height}`}
          preserveAspectRatio="none"
          aria-hidden
        >
          {edges.map(([a, b]) => {
            const lit = isOnChain(a, b);
            return (
              <line
                key={`${a}-${b}`}
                x1={xOf(a)}
                y1={yOf(a)}
                x2={xOf(b)}
                y2={yOf(b)}
                stroke={lit ? "#c19d6c" : "#3f3b36"}
                strokeWidth={lit ? 2 : 1}
                vectorEffect="non-scaling-stroke"
                opacity={activeId != null && !lit ? 0.45 : 1}
              />
            );
          })}
        </svg>

        {edges.map(([a, b]) => {
          if (!(showAllEdgeDegrees || isOnChain(a, b))) return null;
          const deg = byId.get(b).subgroup_order / byId.get(a).subgroup_order;
          return (
            <span
              key={`d-${a}-${b}`}
              className="absolute -translate-x-1/2 -translate-y-1/2 px-1 text-[10px] leading-4 bg-black text-accent-400 pointer-events-none"
              style={{ left: `${((xOf(a) + xOf(b)) / 2 / VIEWBOX_W) * 100}%`, top: (yOf(a) + yOf(b)) / 2 }}
            >
              {deg}
            </span>
          );
        })}

        {nodes.map((n) => {
          const isActive = n.id === activeId;
          const related = above.has(n.id) || below.has(n.id);
          const dim = activeId != null && !isActive && !related;
          return (
            <button
              key={n.id}
              type="button"
              onMouseEnter={() => onHover(n.id)}
              onFocus={() => onHover(n.id)}
              onClick={() => onSelect(n.id)}
              className={`absolute -translate-x-1/2 -translate-y-1/2 px-2 py-1 border whitespace-nowrap text-sm transition-colors duration-100 ${
                isActive
                  ? "bg-accent-400 border-accent-400 text-black"
                  : related
                    ? "bg-gray-950 border-accent-400 text-gray-50"
                    : n.normal
                      ? "bg-gray-950 border-gray-400 text-gray-100"
                      : "bg-gray-950 border-gray-700 border-dashed text-gray-200"
              } ${dim ? "opacity-40" : ""}`}
              style={{ left: `${(xOf(n.id) / VIEWBOX_W) * 100}%`, top: yOf(n.id) }}
            >
              <MathDisplay inline>{fieldsView ? n.field_latex : n.group_latex}</MathDisplay>
              {n.class_size > 1 && (
                <span className={`absolute -top-2 -right-2 px-0.5 text-[9px] leading-3 border ${isActive ? "bg-black text-accent-300 border-accent-400" : "bg-black text-gray-500 border-gray-700"}`}>
                  {n.class_position + 1}/{n.class_size}
                </span>
              )}
            </button>
          );
        })}
      </div>
    </div>
  );
}

const ViewToggle = ({ view, onChange }) => (
  <div className="flex border border-gray-700 text-xs uppercase tracking-widest">
    {[
      ["fields", "Subfields of L"],
      ["groups", "Subgroups of G"],
    ].map(([key, label]) => (
      <button
        key={key}
        type="button"
        onClick={() => onChange(key)}
        className={`px-3 py-1.5 whitespace-nowrap transition-colors duration-100 ${
          view === key ? "bg-accent-400 text-black" : "text-gray-300 hover:text-accent-300"
        }`}
      >
        {label}
      </button>
    ))}
  </div>
);

export default function LatticeCard({ lattice, loading, error }) {
  const [view, setView] = useState("fields");
  const [hovered, setHovered] = useState(null);
  const [selected, setSelected] = useState(null);

  const activeId = hovered ?? selected;
  const activeNode = lattice?.nodes?.find((n) => n.id === activeId) ?? null;

  return (
    <Card className="animate-fadeIn">
      <CardContent>
        <SectionTitle icon={LatticeIcon} right={lattice?.available && <ViewToggle view={view} onChange={setView} />}>
          Galois correspondence
        </SectionTitle>

        {loading && (
          <div className="flex items-center gap-3 py-8 justify-center text-accent-400">
            <Spinner className="w-5 h-5" />
            <span className="text-gray-300">Computing subgroups and fixed fields…</span>
          </div>
        )}

        {!loading && error && (
          <p className="text-red-300 text-sm">
            <MathText>{error}</MathText>
          </p>
        )}

        {!loading && lattice && !lattice.available && (
          <p className="text-gray-400 text-sm">
            <MathText>{lattice.reason}</MathText>
          </p>
        )}

        {!loading && lattice?.available && (
          <div className="space-y-4">
            <p className="text-sm text-gray-400 leading-relaxed">
              Each subgroup <MathDisplay inline>{"H \\le G = \\mathrm{Gal}(L/\\mathbb{Q})"}</MathDisplay> corresponds
              to the field <MathDisplay inline>{"L^H"}</MathDisplay> it fixes. The correspondence reverses inclusion,
              so the subgroup lattice is the subfield lattice turned upside down, and{" "}
              <MathDisplay inline>{"[L^H : \\mathbb{Q}] = [G : H]"}</MathDisplay>.
            </p>

            <LatticeDiagram
              lattice={lattice}
              view={view}
              activeId={activeId}
              onHover={setHovered}
              onSelect={(id) => setSelected((cur) => (cur === id ? null : id))}
            />

            <div className="flex flex-wrap gap-x-6 gap-y-1 text-xs text-gray-500">
              <span className="flex items-center gap-2">
                <span className="w-3 h-3 border border-gray-400" /> Galois over <Rationals /> / normal subgroup
              </span>
              <span className="flex items-center gap-2">
                <span className="w-3 h-3 border border-dashed border-gray-600" /> not Galois / not normal
              </span>
              <span className="flex items-center gap-2">
                <span className="text-accent-400">n</span> degree of the extension along an edge
              </span>
              <span className="flex items-center gap-2">
                <span className="text-gray-500">k/m</span> one of m conjugates
              </span>
              <span>
                Automorphisms are written as permutations of the roots{" "}
                <MathDisplay inline>{"\\alpha_1, \\ldots, \\alpha_n"}</MathDisplay> below.
              </span>
            </div>

            {lattice.roots?.length > 0 && (
              <div className="text-xs text-gray-400 space-y-1.5">
                <span className="uppercase tracking-widest text-gray-500">Roots of f</span>
                <RootList roots={lattice.roots} notes={lattice.root_notes} compact />
              </div>
            )}

            <Panel>
              <NodeDetails node={activeNode} groupOrder={lattice.group_order} />
            </Panel>
          </div>
        )}
      </CardContent>
    </Card>
  );
}
